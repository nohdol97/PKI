// I05-C3 ① and I05-C4 ⑦ `workspace.site-packages` (I05-R3, R4, R25): the two workspace lines for a fork's
// packages, and the name check that keeps a package under `site/` out of the `@pki/` range the boundary rule
// treats as public. The root is an argument: each shape of `site/` is a temporary root.
import { mkdirSync, mkdtempSync, rmSync, writeFileSync } from "node:fs";
import { tmpdir } from "node:os";
import { dirname, join, resolve } from "node:path";
import { afterEach, beforeEach, describe, expect, it } from "vitest";
import { forkNameProblems, workspaceGlobs } from "./packages.ts";

const REAL_ROOT = resolve(import.meta.dirname, "../..");
let root: string;
beforeEach(() => void (root = mkdtempSync(join(tmpdir(), "pki-site-packages-"))));
afterEach(() => rmSync(root, { recursive: true, force: true }));

function write(rel: string, text: string) {
  mkdirSync(dirname(join(root, rel)), { recursive: true });
  writeFileSync(join(root, rel), text);
}
const named = (dir: string, name?: string) =>
  write(`${dir}/package.json`, JSON.stringify(name === undefined ? {} : { name }));

describe("workspace.site-packages", () => {
  it("the public workspace lists the composition package and the collector packages as two lines of `packages:`", () => {
    const globs = workspaceGlobs(REAL_ROOT);
    expect(globs).toEqual(expect.arrayContaining(["site/composition", "site/connectors/*"]));
    expect(globs.filter((g) => g.startsWith("site/"))).toHaveLength(2);
  });

  it("reads only the `packages:` list, not the lines after it", () => {
    write(
      "pnpm-workspace.yaml",
      "packages:\n  - backend\n  - 'site/connectors/*'\nallowBuilds:\n  - not-a-glob\n",
    );
    expect(workspaceGlobs(root)).toEqual(["backend", "site/connectors/*"]);
  });

  it("finds nothing to name-check where `site/` holds only the notice, or only an empty connectors folder", () => {
    write("pnpm-workspace.yaml", "packages:\n  - site/composition\n  - site/connectors/*\n");
    write("site/README.md", "notice");
    expect(forkNameProblems(root)).toEqual([]);
    mkdirSync(join(root, "site/connectors"), { recursive: true });
    expect(forkNameProblems(root)).toEqual([]);
  });

  describe("in a fork-shaped tree", () => {
    beforeEach(() =>
      write("pnpm-workspace.yaml", "packages:\n  - site/composition\n  - site/connectors/*\n"),
    );

    it("accepts the composition package and collectors in the fork's range", () => {
      named("site/composition", "@pki-site/composition");
      named("site/connectors/x", "@pki-site/connector-x");
      expect(forkNameProblems(root)).toEqual([]);
    });

    it("fails a collector named in the public range", () => {
      named("site/connectors/x", "@pki/x");
      expect(forkNameProblems(root)).toEqual([
        "site/connectors/x is named @pki/x: a package under site/connectors must be named @pki-site/…",
      ]);
    });

    it("fails a composition package that is not named @pki-site/composition", () => {
      named("site/composition", "@pki-site/other");
      expect(forkNameProblems(root)).toEqual([
        "site/composition is named @pki-site/other: the composition package must be named @pki-site/composition",
      ]);
      named("site/composition", "@pki/composition");
      expect(forkNameProblems(root)).toHaveLength(1);
    });

    it("fails a package with no name", () => {
      named("site/connectors/x");
      expect(forkNameProblems(root)).toHaveLength(1);
    });

    it("leaves public packages alone", () => {
      write("pnpm-workspace.yaml", "packages:\n  - backend\n  - site/connectors/*\n");
      named("backend", "@pki/backend");
      expect(forkNameProblems(root)).toEqual([]);
    });
  });

  it("holds in the real checkout, with or without a `site/` folder beyond the notice", () => {
    expect(forkNameProblems(REAL_ROOT)).toEqual([]);
  });
});
